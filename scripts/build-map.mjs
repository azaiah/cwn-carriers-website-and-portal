// Precomputes state outlines for the lanes map (keeps topojson out of the bundle)
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoMercator, geoPath } from 'd3-geo'
const topo = JSON.parse(readFileSync('node_modules/us-atlas/states-10m.json', 'utf8'))
const states = feature(topo, topo.objects.states)
const keep = { '51': 'VA', '37': 'NC', '24': 'MD', '11': 'DC', '10': 'DE', '54': 'WV', '45': 'SC', '42': 'PA', '34': 'NJ', '47': 'TN', '21': 'KY', '13': 'GA' }
const W = 1000, H = 760
const frame = { type: 'FeatureCollection', features: states.features.filter(f => ['51', '37', '24', '11', '10'].includes(f.id)) }
const proj = geoMercator().fitExtent([[40, 30], [W - 40, H - 30]], frame)
const path = geoPath(proj)
const out = states.features.filter(f => keep[f.id]).map(f => ({ id: keep[f.id], d: path(f).replace(/(\d+\.\d{1})\d+/g, '$1') }))
const ts = `// generated by scripts/build-map.mjs\nexport const MAP_W = ${W}\nexport const MAP_H = ${H}\nexport const MAP_SCALE = ${proj.scale()}\nexport const MAP_TRANSLATE: [number, number] = [${proj.translate()}]\nexport const STATES: { id: string; d: string }[] = ${JSON.stringify(out)}\n`
writeFileSync('src/components/mapdata.ts', ts)
console.log('ok', (ts.length / 1024).toFixed(1) + 'KB')
