import { Link } from 'react-router-dom'
import { Ban, CalendarClock, Printer, Target, TrendingUp } from 'lucide-react'
import { usePortal } from '../store'
import { loadStats } from '../calc'
import { PageHead, Panel, Verdict, daysUntil, shortDate, usd } from '../../components/ui'
import { brainCompleteness } from '../../brain/score'

export default function Briefing() {
  const { scored, loads, brain, compliance } = usePortal()
  const st = loadStats(loads, brain)
  const goes = scored.filter(o => o.s.verdict === 'Go' && !['passed', 'won', 'lost'].includes(o.status))
  const deadlines = scored.filter(o => { const d = daysUntil(o.dueDate); return o.kind === 'bid' && d !== null && d >= 0 && d <= 14 && o.s.verdict !== 'Pass' }).sort((a, b) => (a.dueDate ?? '').localeCompare(b.dueDate ?? ''))
  const passes = scored.filter(o => o.s.verdict === 'Pass').slice(0, 4)
  const todo = compliance.filter(c => c.status !== 'ok')
  const pct = Math.round(st.weekRevenue / st.weeklyTarget * 100)
  const monday = new Date(); monday.setDate(monday.getDate() - ((monday.getDay() + 6) % 7))

  const moves = [
    ...deadlines.slice(0, 2).map(o => `Respond to "${o.title}" (${o.org}), due ${shortDate(o.dueDate)}.`),
    ...goes.filter(o => !o.sample && (o.kind === 'lead' || o.kind === 'partner')).slice(0, 2).map(o => `Reach out to ${o.org}: ${o.title.toLowerCase()}. ${o.why?.split('. ')[0] ?? ''}.`),
    ...(brain.registrations.sam ? [] : ['Start SAM.gov registration. It unlocks every federal bid in the feed and can take 2–4 weeks.']),
    ...(brain.insurance.cargo === null ? ['Get a cargo insurance quote ($100K is the common broker ask). It clears a flag on several leads.'] : []),
  ].slice(0, 5)

  return (
    <>
      <PageHead eyebrow={`Week of ${monday.toLocaleDateString(undefined, { month: 'long', day: 'numeric' })}`} title="Weekly briefing" sub="Generated by the Company Brain every Monday at 6 AM. What happened, what matters, and the moves to make."
        right={import.meta.env.MODE !== 'preview' && <button onClick={() => window.print()} className="btn btn-ghost btn-sm no-print"><Printer size={14} /> Print / PDF</button>} />

      <div className="grid md:grid-cols-4 gap-px bg-white/10 mb-4">
        {[['Revenue · 7 days', usd(st.weekRevenue), `${pct}% of target`], ['30-day margin', usd(st.monthMargin), `$${st.rpm.toFixed(2)}/mi avg rate`], ['Go opportunities', String(goes.length), `${deadlines.length} deadlines in 14 days`], ['Brain knowledge', brainCompleteness(brain) + '%', `${brain.unknowns.length} facts open`]].map(([k, v, h]) => (
          <div key={k} className="bg-onyx-850 p-5"><div className="label">{k}</div><div className="font-display font-extrabold text-[34px] leading-none">{v}</div><div className="text-[13px] text-graphite-300 mt-1.5">{h}</div></div>
        ))}
      </div>

      <div className="grid lg:grid-cols-[1.3fr_1fr] gap-4">
        <Panel title={<span className="flex items-center gap-2"><Target size={16} className="text-crimson-400" /> Your moves this week</span>}>
          <ol className="space-y-4">
            {moves.map((m, i) => (
              <li key={i} className="flex gap-4"><span className="font-display font-extrabold text-[30px] leading-none text-crimson-400 w-7">{i + 1}</span><p className="text-[15.5px] leading-relaxed pt-1">{m}</p></li>
            ))}
          </ol>
        </Panel>
        <Panel title={<span className="flex items-center gap-2"><CalendarClock size={16} className="text-signal-amber" /> Deadlines</span>}>
          <ul className="divide-y divide-white/[.05] -my-2">
            {deadlines.map(o => (
              <li key={o.id} className="py-2.5 flex items-center gap-3">
                <div className="w-14 text-center"><div className="font-display font-extrabold text-[22px] leading-none">{daysUntil(o.dueDate)}</div><div className="text-[10px] font-mono text-graphite-400">DAYS</div></div>
                <Link to={`/portal/opportunities?id=${o.id}`} className="flex-1 min-w-0"><div className="text-[14px] font-semibold truncate">{o.title}</div><div className="text-[12px] text-graphite-400 truncate">{o.org}</div></Link>
                <Verdict v={o.s.verdict} />
              </li>
            ))}
            {!deadlines.length && <li className="py-4 text-graphite-300 text-sm">No bid deadlines in the next two weeks.</li>}
          </ul>
        </Panel>
        <Panel title={<span className="flex items-center gap-2"><TrendingUp size={16} className="text-signal-green" /> Best new opportunities</span>}>
          <ul className="space-y-3">
            {goes.slice(0, 5).map(o => (
              <li key={o.id}><Link to={`/portal/opportunities?id=${o.id}`} className="flex items-start gap-3 group"><span className="font-display font-extrabold text-[22px] w-9 text-signal-green">{o.s.score}</span><div><div className="text-[14.5px] font-semibold group-hover:text-crimson-400">{o.title}</div><div className="text-[12.5px] text-graphite-300">{o.org} · {usd(o.estValue)}{o.valueBasis === 'annual' ? '/yr' : ''}</div></div></Link></li>
            ))}
          </ul>
        </Panel>
        <Panel title={<span className="flex items-center gap-2"><Ban size={16} className="text-graphite-300" /> What the Brain passed on, and why</span>}>
          <ul className="space-y-3">
            {passes.map(o => <li key={o.id}><div className="text-[14px] font-semibold">{o.title}</div><div className="text-[12.5px] text-crimson-400">{o.s.reasons.find(r => r.kind === 'stop')?.text ?? o.s.reasons.find(r => r.kind === 'minus')?.text}</div></li>)}
          </ul>
          <p className="text-[12.5px] text-graphite-400 mt-4">Pattern: reefer, CDL and 53' work keeps showing up nearby. Worth factoring into the truck #3 decision.</p>
        </Panel>
      </div>

      <Panel title="Housekeeping" className="mt-4">
        <div className="grid md:grid-cols-2 gap-x-8 gap-y-2">
          {todo.map(t => <div key={t.id} className="flex gap-3 py-1.5 text-[14px]"><span className={`w-1.5 shrink-0 ${t.status === 'missing' ? 'bg-crimson' : 'bg-signal-amber'}`} /><span><b>{t.item}</b>: <span className="text-graphite-300">{t.detail}</span></span></div>)}
        </div>
      </Panel>
    </>
  )
}
